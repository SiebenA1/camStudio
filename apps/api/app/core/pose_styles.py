def get_style(style_id: str | None) -> dict | None:
    """按 id 取风格；未知或为空返回 None。"""
    if not style_id:
        return None
    for s in POSE_STYLES:
        if s["id"] == style_id:
            return s
    return None


def list_styles() -> list[dict]:
    """返回给前端的风格库（不含 poses，界面只展示 label；poses 在选择后由后端使用）。"""
    return [{"id": s["id"], "label": s["label"], "hint": s["hint"]} for s in POSE_STYLES]
